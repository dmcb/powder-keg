function randomFromWordLists(adjectives: string[], nouns: string[]): string {
  const adjective = adjectives[Math.floor(Math.random() * adjectives.length)];
  const noun = nouns[Math.floor(Math.random() * nouns.length)];
  return adjective + noun;
}

export function generateGameSeed(): string {
  return randomFromWordLists(gameSeedAdjectives, gameSeedNouns);
}

export function generatePlayerName(): string {
  return randomFromWordLists(playerNameAdjectives, playerNameNouns);
}
